def run_setup(args) -> int:
    """Main entry point for `importer setup` command."""
    home_dir = config.home()
    is_interactive = not getattr(args, "non_interactive", False) and sys.stdin.isatty()

    if is_interactive:
        print("\n" + "=" * 65)
        print(" Data Import Agent (MCP) — Setup & Standup Wizard")
        print("=" * 65)

    # 1. Existing configuration check
    existing_doc: dict[str, Any] = {}
    env_file = home_dir / "database.env"
    if env_file.exists():
        try:
            existing_doc = db.load_connection_document(env_file)
        except Exception:
            pass

    # 2. Check if user has a SQL Server
    if is_interactive and not env_file.exists() and not getattr(args, "server", None):
        has_server = _prompt_bool("Do you have a SQL Server instance running?", default=True)
        if not has_server:
            print(DOCKER_INSTRUCTIONS)
            choice = _prompt("Press Enter to continue setup once started, or 'q' to quit", default="")
            if choice.lower() == "q":
                return 0

    # 3. Resolve connection parameters
    server = getattr(args, "server", None) or existing_doc.get("server")
    database = getattr(args, "database", None) or existing_doc.get("database") or "import_agent_dev"
    auth = getattr(args, "auth", None)
    user = getattr(args, "user", None) or existing_doc.get("UN")
    password = getattr(args, "password", None) or existing_doc.get("PW")
    save_password = getattr(args, "save_password", False)
    auto_create = getattr(args, "create_db", False)
    skip_schema = getattr(args, "skip_schema", False)

    if is_interactive:
        server = _prompt("SQL Server hostname or IP", default=server or "localhost")
        database = _prompt("Control database name", default=database)

        default_auth_choice = "2" if existing_doc.get("trusted") in ("yes", True) else "1"
        print("\nSelect Authentication Method:")
        print("  1) SQL Server Authentication (username + password)")
        print("  2) Windows Integrated Authentication (Trusted Connection)")
        print("  3) Microsoft Entra ID / Azure Active Directory")
        auth_choice = _prompt("Choose [1-3]", default=default_auth_choice)

        if auth_choice == "2":
            auth = "trusted"
            user = None
            password = None
        elif auth_choice == "3":
            auth = "entra"
            user = _prompt("Entra username / UPN", default=user or "")
            password = None
        else:
            auth = "sql"
            user = _prompt("SQL Server username", default=user or "sa")
            if not password:
                password = getpass.getpass("SQL Server password: ")
            save_password = _prompt_bool("Save password in database.env on disk?", default=False)
            if not save_password:
                print(" -> Password will NOT be saved to disk.")
                print("    You will be prompted when running CLI commands interactively,")
                print("    or you can set the IMPORTER_PASSWORD environment variable for MCP/headless runs.")
    else:
        if not server:
            server = "localhost"
        if not auth:
            auth = "sql" if user else "trusted"

    # Build connection dictionary
    doc: dict[str, Any] = {
        "type": "mssql",
        "server": server,
        "database": database,
        "TrustServerCertificate": "yes",
    }
    if auth == "trusted":
        doc["trusted"] = "yes"
    elif auth == "entra":
        doc["UN"] = user
        doc["auth"] = "ActiveDirectoryInteractive"
    else:
        # SQL Server auth
        doc["UN"] = user
        if save_password and password:
            doc["PW"] = password

    # Cache password in session for current setup process
    if password:
        db.set_session_password(password)

    # 4. Check or create database
    test_doc = dict(doc)
    if password:
        test_doc["PW"] = password

    print(f"\nTesting connection to {server}...")
    db_ready = check_or_create_database(
        server=server,
        database=database,
        doc=test_doc,
        auto_create=auto_create,
        interactive=is_interactive,
    )
    if not db_ready:
        print("Setup aborted: Unable to connect to or create the database.", file=sys.stderr)
        return 1

    # 5. Write database.env
    env_written = write_database_env(home_dir, doc)
    print(f"Configuration written to {env_written.name}.")

    # 6. Apply schema & environment
    if not skip_schema:
        engine = db._connection_engine(name="importer_setup", server=server, database=database, doc=test_doc)
        dev_rebuild = False
        if is_interactive and "dev" in database.lower():
            dev_rebuild = False  # default no rebuild if already existing
        apply_schema(engine, dev_rebuild=dev_rebuild)

    # 7. Print summary and instructions
    if is_interactive:
        print_mcp_instructions(server, database, pw_saved=bool(save_password and password))

    return 0

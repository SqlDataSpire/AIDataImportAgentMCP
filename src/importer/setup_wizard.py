def _prompt(text: str, default: str | None = None) -> str:
    """Prompt the user with an optional default value."""
    suffix = f" [{default}]: " if default is not None else ": "
    try:
        val = input(text + suffix).strip()
    except (EOFError, KeyboardInterrupt):
        print("\nSetup cancelled.")
        sys.exit(1)
    return val if val else (default or "")


def _prompt_bool(text: str, default: bool = False) -> bool:
    """Prompt the user for a yes/no question."""
    suffix = " [Y/n]: " if default else " [y/N]: "
    try:
        val = input(text + suffix).strip().lower()
    except (EOFError, KeyboardInterrupt):
        print("\nSetup cancelled.")
        sys.exit(1)
    if not val:
        return default
    return val in ("y", "yes", "1", "true")


def _ensure_gitignore(home_dir: Path) -> None:
    """Ensure database.env is listed in .gitignore."""
    gitignore_path = home_dir / ".gitignore"
    if gitignore_path.exists():
        content = gitignore_path.read_text(encoding="utf-8")
        if "database.env" not in content:
            with gitignore_path.open("a", encoding="utf-8") as f:
                f.write("\n# Database credentials\ndatabase.env\n")
    else:
        gitignore_path.write_text("# Database credentials\ndatabase.env\n", encoding="utf-8")


def write_database_env(home_dir: Path, connection_doc: dict[str, Any]) -> Path:
    """Write or update database.env file with the connection document."""
    env_path = home_dir / "database.env"
    payload = {"databases": {"importer": connection_doc}}
    # Format cleanly as .env key=value
    content = (
        "# Data Import Agent MCP - Database Configuration\n"
        "# Generated by: importer setup\n"
        f"databases = '{json.dumps(payload['databases'])}'\n"
    )
    env_path.write_text(content, encoding="utf-8")
    _ensure_gitignore(home_dir)
    return env_path


def check_or_create_database(
    *,
    server: str,
    database: str,
    doc: dict[str, Any],
    auto_create: bool = False,
    interactive: bool = True,
) -> bool:
    """Check if database exists; if not, offer to create it via master database."""
    from sqlalchemy import text

    # Try connecting directly to master to check DB_ID
    master_doc = dict(doc)
    master_doc["database"] = "master"
    try:
        master_engine = db._connection_engine(name="master_check", server=server, database="master", doc=master_doc)
        with master_engine.connect() as conn:
            db_id = conn.execute(text("SELECT DB_ID(:name)"), {"name": database}).scalar_one_or_none()
            if db_id is not None:
                return True

            # Database does not exist on master
            create = auto_create
            if not create and interactive:
                create = _prompt_bool(f"Database '{database}' does not exist on {server}. Create it now?", default=True)

            if create:
                print(f"Creating database [{database}] on {server}...")
                conn.execution_options(isolation_level="AUTOCOMMIT").exec_driver_sql(f"CREATE DATABASE [{database}]")
                print(f"Database [{database}] created successfully.")
                return True
            else:
                print(f"Database [{database}] was not created.")
                return False
    except Exception:
        # If connecting to master failed or user doesn't have master access, try direct connection to target DB
        try:
            target_engine = db._connection_engine(name="target_check", server=server, database=database, doc=doc)
            with target_engine.connect():
                return True
        except Exception as direct_exc:
            print(f"Failed to connect to database '{database}' on {server}: {direct_exc}", file=sys.stderr)
            return False


def apply_schema(engine, *, dev_rebuild: bool = False) -> None:
    """Initialize database_identity and apply 001_schema.sql."""
    from sqlalchemy import text

    # 1. Check/Init identity
    with engine.connect() as conn:
        identity = environment.read(conn)
    if identity.environment is None:
        with engine.begin() as conn:
            environment.init(conn, "DEV", by=getpass.getuser())
            print("Marked database environment as DEV.")
    else:
        print(f"Database environment is already marked as {identity.environment}.")

    # 2. Check if tables exist
    with engine.connect() as conn:
        has_schema = conn.execute(text("SELECT OBJECT_ID(N'dbo.artifact_versions')")).scalar_one_or_none() is not None

    schema_sql_path = config.home() / "sql" / "001_schema.sql"
    if not schema_sql_path.exists():
        schema_sql_path = Path(__file__).resolve().parent / "sql" / "001_schema.sql"
    if not schema_sql_path.exists():
        print(f"Warning: schema file not found at {schema_sql_path}", file=sys.stderr)
        return

    script = schema_sql_path.read_text(encoding="utf-8")

    if not has_schema or dev_rebuild:
        with engine.begin() as conn:
            if dev_rebuild:
                conn.exec_driver_sql(REBUILD_DROP_SQL)
            conn.exec_driver_sql(script)
        action = "Rebuilt" if dev_rebuild else "Applied"
        print(f"{action} control-plane schema (sql/001_schema.sql).")
    else:
        print("Control-plane tables already exist. Skipping schema deploy.")


